"""Regulatory and investor-protection guardrails.

The application is an analysis assistant, not a SEBI-registered investment adviser or
research analyst. This module holds the disclaimer and the rules that keep model output
on the right side of that line:

* every report and valuation output carries DISCLAIMER;
* LLM system prompts include COMPLIANCE_RULES;
* `screen_output` flags personalised advice or guaranteed-return language in generated
  text and appends a compliance note, so it is never shown unqualified.

None of this is a legal opinion: compliance must be reviewed before any public or
commercial deployment.
"""

import re
from dataclasses import dataclass, field

DISCLAIMER = (
    "This report is generated by an AI-based financial analysis system for informational and "
    "educational purposes only. It is based on publicly available information, including company "
    "disclosures, and uses analytical models and assumptions that may contain limitations or errors. "
    "The valuations and price estimates presented are model-generated estimates and are not guaranteed "
    "outcomes. This report does not constitute personalized investment advice, a recommendation to buy, "
    "sell, or subscribe to any security, or an offer or solicitation to invest. Users should independently "
    "verify the information, consider their financial circumstances and risk tolerance, and consult an "
    "appropriately qualified and registered financial professional where necessary before making "
    "investment decisions."
)

VALUATION_NOTICE = (
    "Model-generated estimate. This is not the official IPO issue price and not a forecast of the listing "
    "price. Actual prices depend on demand, supply, investor sentiment and market conditions."
)

LISTING_NOTICE = (
    "Any listing-price scenario is a model estimate, not a guaranteed market price. Actual listing prices "
    "depend on market demand, supply, investor sentiment, market conditions and other factors."
)

COMPLIANCE_RULES = """\
You are an AI analysis assistant for IPO offer documents. You are NOT a SEBI-registered investment
adviser, research analyst or merchant banker, and must never present yourself as one.
Rules:
1. Do not give personalised investment advice. Never tell the user to buy, sell, subscribe to, apply
   for or avoid an IPO or security. If asked "should I invest/subscribe", explain that you cannot give
   a personalised recommendation, then offer the relevant evidence-based analysis and risks.
2. Never promise or imply guaranteed returns, listing gains or future prices.
3. Every factual statement about the company must be supported by the provided evidence and cited.
   If the evidence does not contain the answer, say clearly that it was not found in the document.
4. Never invent figures, page numbers, peer data, subscription data, grey market premium (GMP),
   listing prices or regulatory requirements. Do not state what SEBI rules require unless the
   evidence quotes them; otherwise say the requirement needs further review.
5. Distinguish facts extracted from the document from model-generated estimates, and label estimates.
6. Do not minimise or omit material risks.
"""

# Personalised-advice and guaranteed-outcome phrasings. Kept narrow on purpose: the
# analysis may legitimately say "investors should note the risks" or quote the DRHP.
_ADVICE_PATTERNS = [
    r"\byou should (?:definitely |strongly )?(?:buy|sell|subscribe|apply|invest|avoid|skip)\b",
    r"\bi (?:would )?(?:recommend|suggest|advise) (?:you )?(?:to )?(?:buy|sell|subscribe|apply|invest|avoid)\b",
    r"\b(?:we )?recommend (?:buying|selling|subscribing|applying|investing)\b",
    r"\b(?:strong |a )?(?:buy|sell|subscribe|avoid) (?:rating|recommendation|call)\b",
    r"\bmust (?:buy|subscribe|apply)\b",
    r"\bgo for (?:this|the) ipo\b",
]
_GUARANTEE_PATTERNS = [
    r"\bguaranteed? (?:returns?|gains?|profits?|listing)\b",
    r"\b(?:will|is certain to|is sure to) (?:definitely )?list (?:at|above) (?:a )?(?:premium|profit)\b",
    r"\brisk[- ]free (?:returns?|investment|gains?)\b",
    r"\bsure[- ]shot\b",
    r"\bcannot lose\b",
]

COMPLIANCE_NOTE = (
    "Compliance note: part of this answer used language that could read as a personalised recommendation "
    "or a guaranteed outcome. It is not one. This tool provides analysis only, not investment advice; "
    "listing prices and returns are never guaranteed."
)


@dataclass
class ScreenResult:
    """Outcome of screening generated text."""

    text: str
    flagged: bool = False
    matches: list[str] = field(default_factory=list)


def screen_output(text: str) -> ScreenResult:
    """Flag personalised-advice or guaranteed-outcome language and append a compliance note."""
    low = text.lower()
    matches = [m.group(0) for pat in _ADVICE_PATTERNS + _GUARANTEE_PATTERNS for m in re.finditer(pat, low)]
    if not matches:
        return ScreenResult(text=text)
    return ScreenResult(text=f"{text.rstrip()}\n\n{COMPLIANCE_NOTE}", flagged=True, matches=matches)


_ACT = r"(?:buy|sell|subscribe|apply|invest|bid|participate)"
_ADVICE_QUESTION = re.compile(
    rf"\b(?:should|shall|can|could|may|must) (?:i|we) {_ACT}\b"
    rf"|\b(?:would|will) you (?:buy|recommend|subscribe|invest|apply|advise)\b"
    rf"|\b(?:do|would) you (?:recommend|advise|suggest)\b"
    r"|\bis it (?:a )?(?:good|bad|wise|safe|right) (?:time |idea |bet )?to\b"
    r"|\bis (?:this|the|it) (?:ipo |issue |stock |company )?(?:a )?(?:good|bad|safe|worth) (?:ipo|buy|investment|bet|to (?:buy|invest|subscribe|apply))\b"
    r"|\bworth (?:buying|investing|subscribing|applying|bidding)\b"
    rf"|\b{_ACT} (?:for |in |to )?(?:this|the|that) (?:ipo|issue|stock|shares?|offer)\b"
    r"|\bshould i\b|\bwhich (?:ipo|stock)s? (?:should|to) (?:i )?(?:buy|pick|choose)\b",
    re.IGNORECASE,
)


def is_advice_request(question: str) -> bool:
    """True when the user asks for a personalised buy/sell/subscribe decision.

    Process questions ("Where can I apply?", "How do I bid?") ask how the offer works, not
    whether to take part, so they are not treated as advice requests.
    """
    q = question.strip()
    if re.match(r"(where|how|when)\b", q, re.I) and not re.search(r"\bshould (i|we)\b", q, re.I):
        return False
    return bool(_ADVICE_QUESTION.search(q))


